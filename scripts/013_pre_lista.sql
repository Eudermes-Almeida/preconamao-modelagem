-- Recalcula o item de TODOS os produtos (idempotente). Chamada no fim de cada carga do
-- PRICETAB (ver tools/carga_pricetab.py) e sempre que os termos mudarem. Devolve quantos
-- produtos ficaram vinculados a algum item.
CREATE OR REPLACE FUNCTION vincular_produtos_pre_lista() RETURNS INTEGER
LANGUAGE plpgsql AS $$
BEGIN
    UPDATE produtos p
       SET pre_lista_item_id = (
            SELECT t.item_id
              FROM pre_lista_termo t
             WHERE upper(unaccent(p.descricao)) = t.termo
                OR upper(unaccent(p.descricao)) LIKE t.termo || ' %'
             ORDER BY length(t.termo) DESC
             LIMIT 1);
    RETURN (SELECT count(*) FROM produtos WHERE pre_lista_item_id IS NOT NULL);
END;
$$;

