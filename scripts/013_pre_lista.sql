-- Pré-lista de compras inteligente.
-- O cliente monta em casa uma lista de intenções genéricas ("Detergente", "Arroz"), agrupadas
-- em categorias; no mercado, cada produto bipado risca o item correspondente. O vínculo
-- produto -> item é resolvido aqui no banco, por HERANÇA TEXTUAL: cada item tem termos
-- (início de descrição, MAIÚSCULO e sem acento) e o produto pertence ao item do termo MAIS
-- LONGO que casa com o começo da sua descrição, em palavra inteira:
--   "SABONETE LIQUIDO PROTEX REFIL 200ML" -> Sabonete líquido (termo SABONETE LIQUIDO)
--   "SABONETE DOVE ORIGINAL 90G"          -> Sabonete barra   (termo genérico SABONETE)
-- Fonte única de categorias, itens e termos: tools/pre_lista_seed.py (gera o bloco de INSERTs).
-- Ids fixos, como no layout_posicao: o front guarda na lista do cliente só o id do item.

CREATE TABLE pre_lista_categoria (
    id      INTEGER PRIMARY KEY,
    nome    VARCHAR(60) NOT NULL UNIQUE,
    ordem   INTEGER NOT NULL
);

CREATE TABLE pre_lista_item (
    id            INTEGER PRIMARY KEY,
    categoria_id  INTEGER NOT NULL REFERENCES pre_lista_categoria (id),
    nome          VARCHAR(60) NOT NULL,
    ordem         INTEGER NOT NULL,
    UNIQUE (categoria_id, nome)
);

-- Um termo aponta para um único item, senão o vínculo deixaria de ser determinístico.
CREATE TABLE pre_lista_termo (
    id       SERIAL PRIMARY KEY,
    item_id  INTEGER NOT NULL REFERENCES pre_lista_item (id),
    termo    VARCHAR(40) NOT NULL UNIQUE
);

-- NULL quando nenhum termo casou (produto fora da pré-lista: chocolate, perfume...).
ALTER TABLE produtos ADD COLUMN pre_lista_item_id INTEGER REFERENCES pre_lista_item (id);

