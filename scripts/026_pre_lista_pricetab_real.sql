-- Pré-lista para o PRICETAB real (PRICE2.TXT, análise em analise_pre_lista_PRICE2.xlsx,
-- 2026-10-05): 55% dos produtos não tinham item correspondente. Este script
--   * cria 2 categorias (Doces e Snacks, Tabacaria) e 96 itens (ids 168..263);
--   * acrescenta termos com a grafia do PRICETAB aos itens existentes ("PAO FORMA" para Pão de
--     forma, "SANDALIA HAVAIANAS" para Chinelo...);
--   * "LEITE EM PO" passa do item infantil para o item novo "Leite em pó";
--   * o termo aceita "%" no meio ("LEITE % DESNATADO" = LEITE ... DESNATADO, em qualquer posição
--     depois de LEITE), para os atributos que o PRICETAB põe no fim da descrição.
-- Fonte: tools/pre_lista_seed.py (INSERTs gerados por "python tools/pre_lista_seed.py --atualizar").
-- Depende do 025 (descricao_expandida). Nenhum item é apagado: a pré-lista do cliente fica no
-- celular, pelo id do item.

-- Vínculo produto -> item: o termo mais longo que casa com o começo da descrição expandida, em
-- palavra inteira; "%" no termo = qualquer trecho.
CREATE OR REPLACE FUNCTION vincular_produtos_pre_lista(p_ids BIGINT[] DEFAULT NULL) RETURNS INTEGER
LANGUAGE plpgsql AS $$
BEGIN
    UPDATE produtos p
       SET pre_lista_item_id = (
            SELECT t.item_id
              FROM pre_lista_termo t
             WHERE upper(unaccent(coalesce(p.descricao_expandida, p.descricao))) LIKE t.termo
                OR upper(unaccent(coalesce(p.descricao_expandida, p.descricao))) LIKE t.termo || ' %'
             ORDER BY length(t.termo) DESC
             LIMIT 1)
     WHERE p_ids IS NULL OR p.id = ANY (p_ids);
    RETURN (SELECT count(*) FROM produtos WHERE pre_lista_item_id IS NOT NULL);
END;
$$;

